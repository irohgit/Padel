    // The glyph for a character in this weight (lowercase is drawn as uppercase), or nullptr if there is none
    inline const Glyph* Find(char C, Weight Style)
    {
        if (C >= 'a' && C <= 'z') { C = static_cast<char>(C - 'a' + 'A'); }

        const Glyph* Begin = (Style == Weight::Heavy) ? HEAVY : REGULAR;
        const std::size_t Count = (Style == Weight::Heavy) ? std::size(HEAVY) : std::size(REGULAR);
        for (std::size_t i = 0; i < Count; ++i)
        {
            if (Begin[i].Character == C) { return &Begin[i]; }
        }
        return nullptr;
    }

    inline int Width(const Glyph& G) { return static_cast<int>(std::strlen(G.Rows[0])); }

    inline bool IsLit(const Glyph& G, int Row, int Column)
    {
        return Row >= 0 && Row < ROWS && Column >= 0 && Column < Width(G) && G.Rows[Row][Column] == '#';
    }

    // How far a rounded corner pulls a line in, for a line Distance away from the corner's edge
    inline float CornerInset(float Radius, float Distance)
    {
        const float Rise = Radius - Distance;
        return Radius - std::sqrt(Radius * Radius - Rise * Rise);
    }

    // One cell, with any of its four corners rounded, drawn as 1-pixel horizontal strips
    inline void DrawCell(SDL_Renderer* Renderer, float X, float Y, float Cell,
                         bool RoundTopLeft, bool RoundTopRight, bool RoundBottomLeft, bool RoundBottomRight)
    {
        if (!RoundTopLeft && !RoundTopRight && !RoundBottomLeft && !RoundBottomRight)
        {
            const SDL_FRect Square = { X, Y, Cell, Cell };
            SDL_RenderFillRectF(Renderer, &Square);
            return;
        }

        const float Radius = Cell * CORNER_RADIUS;
        const int   Strips = static_cast<int>(std::ceil(Cell));
        for (int Strip = 0; Strip < Strips; ++Strip)
        {
            const float Height     = (Cell - Strip < 1.0f) ? Cell - Strip : 1.0f;
            const float FromTop    = Strip + 0.5f;
            const float FromBottom = Cell - FromTop;

            float Left = 0.0f, Right = 0.0f;
            if (RoundTopLeft     && FromTop    < Radius) { Left  = std::fmax(Left,  CornerInset(Radius, FromTop)); }
            if (RoundBottomLeft  && FromBottom < Radius) { Left  = std::fmax(Left,  CornerInset(Radius, FromBottom)); }
            if (RoundTopRight    && FromTop    < Radius) { Right = std::fmax(Right, CornerInset(Radius, FromTop)); }
            if (RoundBottomRight && FromBottom < Radius) { Right = std::fmax(Right, CornerInset(Radius, FromBottom)); }

            const SDL_FRect Line = { X + Left, Y + Strip, Cell - Left - Right, Height };
            SDL_RenderFillRectF(Renderer, &Line);
        }
    }

    // Width in pixels of Text at this cell size (one empty cell between characters)
    inline float TextWidth(const char* Text, float Cell, Weight Style = Weight::Heavy)
    {
        int Cells = 0;
        for (const char* C = Text; *C; ++C)
        {
            const Glyph* G = Find(*C, Style);
            Cells += (G ? Width(*G) : SPACE_WIDTH) + 1;
        }
        return Cells > 0 ? (Cells - 1) * Cell : 0.0f;
    }

    // Height in pixels of one line of text at this cell size
    inline float TextHeight(float Cell) { return ROWS * Cell; }

    // Draws Text with its top-left corner at (X, Y)
    inline void DrawText(SDL_Renderer* Renderer, const char* Text, float X, float Y, float Cell,
                         Weight Style = Weight::Heavy)
    {
        for (const char* C = Text; *C; ++C)
        {
            const Glyph* G = Find(*C, Style);
            if (!G) { X += (SPACE_WIDTH + 1) * Cell; continue; }

            for (int Row = 0; Row < ROWS; ++Row)
            {
                for (int Column = 0; Column < Width(*G); ++Column)
                {
                    if (!IsLit(*G, Row, Column)) { continue; }

                    const bool Up    = IsLit(*G, Row - 1, Column);
                    const bool Down  = IsLit(*G, Row + 1, Column);
                    const bool Left  = IsLit(*G, Row, Column - 1);
                    const bool Right = IsLit(*G, Row, Column + 1);

                    // A convex corner: open on two sides, solid on the other two
                    DrawCell(Renderer, X + Column * Cell, Y + Row * Cell, Cell,
                             !Up   && !Left  && Down && Right,
                             !Up   && !Right && Down && Left,
                             !Down && !Left  && Up   && Right,
                             !Down && !Right && Up   && Left);
                }
            }
            X += (Width(*G) + 1) * Cell;
        }
    }

